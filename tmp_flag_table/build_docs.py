from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.oxml.ns import qn
from docx.shared import Pt

doc = Document()
sec = doc.sections[0]
from docx.enum.section import WD_ORIENT
sec.orientation = WD_ORIENT.LANDSCAPE
sec.page_width, sec.page_height = sec.page_height, sec.page_width  # A4 landscape
sec.left_margin = sec.right_margin = Pt(28)
sec.top_margin = sec.bottom_margin = Pt(36)
p = doc.add_paragraph()
p.alignment = WD_ALIGN_PARAGRAPH.CENTER
run = p.add_run("首都北京天安门广场升降国旗时刻表（2026年）")
run.bold = True
run.font.size = Pt(16)
run.font.name = "Times New Roman"
run._element.rPr.rFonts.set(qn("w:eastAsia"), "黑体")

sub = doc.add_paragraph()
sub.alignment = WD_ALIGN_PARAGRAPH.CENTER
sub.add_run("2026年天安门广场升（降）国旗时刻表").bold = True

n_cols = 1 + 24
tbl = doc.add_table(rows=2, cols=n_cols)
tbl.style = "Table Grid"
tbl.alignment = WD_TABLE_ALIGNMENT.CENTER
tbl.autofit = False

# fixed layout so 25 columns fit on one line each
from docx.oxml import OxmlElement
tblPr = tbl._tbl.tblPr
layout = OxmlElement("w:tblLayout")
layout.set(qn("w:type"), "fixed")
tblPr.append(layout)
mar = OxmlElement("w:tblCellMar")
for side, w in (("left", 29), ("right", 29), ("top", 0), ("bottom", 0)):
    e = OxmlElement(f"w:{side}")
    e.set(qn("w:w"), str(w)); e.set(qn("w:type"), "dxa")
    mar.append(e)
tblPr.append(mar)
from docx.shared import Emu
usable = Emu(sec.page_width - sec.left_margin - sec.right_margin)
colw_day = int(usable.pt * 0.027)
colw = int((usable.pt - colw_day) / 24)
tbl.columns[0].width = Pt(colw_day)
for ci in range(1, 25):
    tbl.columns[ci].width = Pt(colw)
for row in tbl.rows:
    row.cells[0].width = Pt(colw_day)
    for ci in range(1, 25):
        row.cells[ci].width = Pt(colw)

def set_cell(cell, text, bold=False, size=9):
    cell.text = ""
    para = cell.paragraphs[0]
    para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = para.add_run(text)
    r.bold = bold
    r.font.size = Pt(size)
    r.font.name = "Times New Roman"
    r._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")

set_cell(tbl.cell(0, 0), "月", bold=True)
set_cell(tbl.cell(1, 0), "日", bold=True)
for m in range(12):
    mc = tbl.cell(0, 1 + m * 2).merge(tbl.cell(0, 2 + m * 2))
    set_cell(mc, f"{CN_MONTH[m]}月", bold=True)
    set_cell(tbl.cell(1, 1 + m * 2), "升", bold=True)
    set_cell(tbl.cell(1, 2 + m * 2), "降", bold=True)

for d in DAYS:
    cells = tbl.add_row().cells
    set_cell(cells[0], str(d), bold=True)
    for m in range(12):
        v = D[m + 1].get(d)
        set_cell(cells[1 + m * 2], v[0] if v else "")
        set_cell(cells[2 + m * 2], v[1] if v else "")

foot = doc.add_paragraph()
fr = foot.add_run("来源：北京市人民政府天安门地区管理委员会（2025-12-22发布）")
fr.font.size = Pt(9)
fr.italic = True
doc.save("2026天安门广场升降国旗时刻表.docx")
print("done")
