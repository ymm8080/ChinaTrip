def test_mailer_en_body_contains_verification_code_and_digits():
    mailer = SmtpMailer(get_settings())
    set_lang("en")
    try:
        msg = mailer._message("traveler@example.com", "654321", "register")
    finally:
        set_lang("zh")
    body = msg.get_payload(decode=True).decode("utf-8")
    assert "verification code" in body
    assert "654321" in body
    assert "ChinaTrip" in body
    subject = str(msg["Subject"])
    assert "verification code" in subject
    assert "654321" in subject
