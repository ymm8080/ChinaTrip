def make_plan() -> ItineraryPlan:
    visit = VisitItem(
        item_id="v1",
        name="故宫",
        city="北京",
        poi_id="poi_1",
        location=GeoPoint(lon=116.397, lat=39.918),
        address="北京市东城区景山前街4号",
        opening_hours="08:30-17:00",
        day=1,
        start_time=dtime(9, 0),
        duration_minutes=120,
        distance_to_next_km=1.2,
        next_walk_minutes=15,
        leg_source="amap",
        pinned=True,
    )
    transfer = TransferItem(
        item_id="t1",
        day=2,
        seq=1,
        from_city="北京",
        to_city="西安",
        mode="train",
        start_time=dtime(8, 0),
        duration_minutes=270,
        train_no="G87",
    )
    return ItineraryPlan(
        itinerary_id="it_en1",
        cities=["北京", "西安"],
        days=[
            DayPlan(day=1, base_city="北京", items=[visit]),
            DayPlan(day=2, base_city="西安", items=[transfer]),
        ],
        assumptions=["假设1：未计入排队时间"],
    )


def test_export_html_en_switches_labels_and_headers():
    set_lang("en")
    try:
        text = render_html(make_plan())
    finally:
        set_lang("zh")
    assert '<html lang="en">' in text
    assert "Itinerary: 北京 → 西安" in text
    assert "Day 1 · 北京" in text and "Day 2 · 西安" in text
    assert "<th>Time</th>" in text
    assert "<th>Itinerary</th>" in text
    assert "<th>Address</th>" in text
    assert "<th>Opening hours</th>" in text
    assert "<th>时间</th>" not in text
    assert "<th>安排</th>" not in text
    assert "Pinned" in text and "已钉住" not in text
    assert "Train/High-speed rail 北京 → 西安" in text
    assert "Generated by ChinaTrip" in text
    assert "Assumptions" in text


def test_export_html_zh_default_unchanged():
    text = render_html(make_plan())
    assert '<html lang="zh-CN">' in text
    assert "行程单：北京 → 西安" in text
    assert "<th>时间</th><th>安排</th>" in text
    assert "第 1 天 · 北京" in text
    assert "由 ChinaTrip 生成" in text


def test_export_docx_and_xlsx_en():
    plan = make_plan()
    set_lang("en")
    try:
        doc = Document(io.BytesIO(render_docx(plan)))
        doc_text = "\n".join(p.text for p in doc.paragraphs)
        ws = load_workbook(io.BytesIO(render_xlsx(plan))).active
    finally:
        set_lang("zh")
    assert "Day 1 · 北京" in doc_text
    assert "📌 Pinned" in doc_text
    assert "Address: 北京市东城区景山前街4号" in doc_text
    assert ws.title == "Itinerary"
    assert ws["A2"].value == "Time"
    flat = {str(c.value) for row in ws.iter_rows() for c in row if c.value is not None}
    assert any("Day 2 · 西安" in v for v in flat)
    assert any("Train/High-speed rail" in v for v in flat)


def make_shared_record() -> ItineraryRecord:
    now = datetime.now(timezone.utc)
    record = ItineraryRecord(
        itinerary_id="it_en_share",
        owner_device_id="devA",
        plan=make_plan(),
        created_at=now,
        updated_at=now,
    )
    record.share_enabled = True
    record.share_token = "tok_en_probe_1234567890"
    return record


def _share_client() -> TestClient:
    app = FastAPI()
    store = InMemoryItineraryStore()
    store.put(make_shared_record())
    app.dependency_overrides[get_store] = lambda: store
    app.dependency_overrides[_account_from_auth] = lambda: None
    app.include_router(share_router)
    return TestClient(app)


def test_share_landing_lang_en_query_switches_page():
    share_mod.reset_public_limiter_for_tests()
    try:
        with _share_client() as client:
            r = client.get("/s/tok_en_probe_1234567890", params={"lang": "en"})
        assert r.status_code == 200
        assert '<html lang="en">' in r.text
        assert "Opening your trip… " in r.text
        assert "Tap to open" in r.text
        assert "正在打开行程" not in r.text
        assert "· ChinaTrip Trip Planner" in r.text
    finally:
        share_mod.reset_public_limiter_for_tests()
        set_lang("zh")


