def coarse_tag(tag: str) -> str:
    """单标签映射；未知词原样透传（不猜桶）。"""
    t = (tag or "").strip()
    return _COARSE_MAP.get(t, t)


def coarse_tags(tags: list | None) -> list[str]:
    """标签数组粗化：保序、去重、透传未知词。None→[]。"""
    out: list[str] = []
    for t in tags or []:
        if not isinstance(t, str):
            continue
        c = coarse_tag(t)
        if c and c not in out:
            out.append(c)
    return out
