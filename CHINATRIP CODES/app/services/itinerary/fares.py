DEFAULT_TARIFF: tuple[float, float, float] = (10.0, 3.0, 2.0)

#: 接驳票价默认值（无逐点票价数据时的保守估价，单位元）
ACCESS_FARE_DEFAULT: dict[str, int] = {
    "shuttle": 20,
    "ferry": 10,
    "train": 5,
}


def _city_key(city: str | None) -> str:
    return str(city or "").strip().removesuffix("市").strip()


def estimate_taxi_fare(
    city: str | None,
    km: float,
    *,
    night: bool = False,
) -> int:
    """按城市价目表估算打车费（元）。km 为计价里程（直线×绕行系数）。"""
    base, base_km, per_km = CITY_TAXI_TARIFF.get(_city_key(city), DEFAULT_TARIFF)
    fare = base + max(0.0, float(km) - base_km) * per_km
    if night:
        fare *= 1.2
    return max(int(round(fare)), int(round(base)))


def access_fare_estimate(mode: str | None) -> int:
    """接驳段（专线/轮渡/铁路）票价默认估价；未知模式按 shuttle 保守值。"""
    return ACCESS_FARE_DEFAULT.get(str(mode or "").strip().lower(), 0)
