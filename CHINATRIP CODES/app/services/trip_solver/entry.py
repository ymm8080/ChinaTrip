logger = logging.getLogger(__name__)

ENGINE_LEGACY = "legacy"
ENGINE_SHADOW = "shadow"
ENGINE_CPSAT = "cpsat"
ENGINES = (ENGINE_LEGACY, ENGINE_SHADOW, ENGINE_CPSAT)
ENV_FLAG = "TRIP_SOLVER"

SHADOW_SAMPLE_RATE = 0.05  # audit M6: ≤ 5% of generations

FALLBACK_DISCLOSURE = {
    "zh": "行程由现行引擎生成（新求解引擎未就绪/已回滚，TRIP_SOLVER=legacy 语义）",
    "en": "Itinerary generated by the current engine (new solver not ready "
    "or rolled back, TRIP_SOLVER=legacy semantics)",
}


class TripSolverError(RuntimeError):
    """Base for entry-adapter failures (fail-loud surface in tests)."""


class ServingNotReady(TripSolverError):
    """flag=cpsat was requested but the serving stack (P1-F assembly) is
    not landed — the caller must keep the cascade serving (M8 shape)."""


def engine_flag(env: Optional[dict] = None) -> str:
    """Resolved engine flag. Unknown values degrade to legacy with a
    warning — a typo in the env var must never half-switch the engine."""
    source = env if env is not None else os.environ
    value = str(source.get(ENV_FLAG, "") or "").strip().lower()
    if value in ENGINES:
        return value
    if value:
        logger.warning(
            "trip_solver: unknown %s=%r — degrading to legacy", ENV_FLAG, value
        )
    return ENGINE_LEGACY


def serving_ready() -> tuple[bool, str]:
    """Whether flag=cpsat can actually SERVE a plan (needs P1-F F-30
    materialisation). Checked before any model work: production never pays
    for a solve it cannot serve."""
    try:
        import app.services.trip_solver.assembly  # noqa: F401
    except ImportError:
        return False, "P1-F assembly not landed (F-30 materialisation missing)"
    return True, ""


def should_sample(key: str, rate: float = SHADOW_SAMPLE_RATE) -> bool:
    """Deterministic sampling gate (M6): stable per key, no RNG state."""

    bucket = int(hashlib.sha1(key.encode("utf-8")).hexdigest()[:8], 16) % 10000
    return bucket < int(rate * 10000)


def seam_plain_shape(
    *,
    brief=None,
    images=None,
    arrival_date=None,
    departure_date=None,
    start_date=None,
    days=None,
    cities=None,
) -> bool:
    """F-35 形状闸（R8 2026-11-18 收窄）：出计划全量切引擎。

    映射类字段不再拦——城际方式（intercity_mode train/flight 由缝
    透传成 TripRequest.arrival_mode/departure_mode）、确认卡 override
    （days/班次号=用户已选边，api 缝折算后透传）、行前卡标志（intake
    纯 opting-in）。仍留 legacy 的是引擎尚无语义的开局形状：
    - 文字路线 brief / 开局带图：读点确认轮（F-03 缝不吞点）；
    - 非默认端点行前日期：到达≠首日/离开≠末日=中途转移日。
    days/cities 齐备才可解（缺=追问轮）。"""
    if (brief or "").strip():
        return False
    if images:
        return False
    if not _intake_dates_at_default_endpoints(
        arrival_date, departure_date, start_date, days
    ):
        return False
    if not days or not cities:
        return False
    return True


def _intake_dates_at_default_endpoints(arrival_date, departure_date, start_date, days):
    """行前日期卡 → 端点日语义（legacy _intake_target_day 同口径）。

    到达=首日/离开=末日（或缺省、映射不了）与引擎默认形状等价，直连；
    中途到达/离开（D2 才到、D3 就走）引擎无对应约束——留 legacy
    （_apply_intake_times 的撤腿重排在那边）。"""
    import datetime as _dt

    def _day_no(iso):
        if not iso or not start_date:
            return None
        try:
            return (
                _dt.date.fromisoformat(str(iso)[:10])
                - _dt.date.fromisoformat(str(start_date)[:10])
            ).days + 1
        except ValueError:
            return None

    if arrival_date:
        arrived = _day_no(arrival_date)
        if arrived is not None and arrived != 1:
            return False
    if departure_date:
        left = _day_no(departure_date)
        if left is not None and (days or 0) and left != days:
            return False
    return True


