"""F-35 entry adapter — the only call path between legacy/api and the new
engine (P3, flag-gated; **code lands first, cutover stays gated**).

``TRIP_SOLVER`` env (M8 rollback = flip it back to ``legacy``; no data
migration — plan/session schemas are unchanged):

- ``legacy`` (default) — the existing cascade serves, untouched. This is
  the only behavior through P1/P2; the adapter is contract + telemetry.
- ``shadow`` — the cascade still serves; the model double-solves purely
  for F-36 telemetry / F-62 evidence. Audit M6 live sampling applies:
  ≤ 5 % of generations, max 1 extra solve per session — gate with
  :func:`should_sample` before calling.
- ``cpsat`` — the model engine serves. Pre-P1-F there is no plan
  materialisation (F-30), so :func:`serving_ready` is False and callers
  keep the cascade serving with a disclosure line — exactly the M8
  rollback shape. Exceptions inside the model path: **fail loud in
  tests**; in production → telemetry + legacy serving with disclosure
  (F-35). The P0 outbound gates run downstream of either engine.

The adapter is synchronous; callers invoke it via ``asyncio.to_thread``
(F-35). P4 edit re-solve passes the previous solution as ``hint``.
"""

from __future__ import annotations

import hashlib
import logging
import os
from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any, Callable, Optional

from .assembly import assemble
from .inputs.enrich import enrich
from .model.solve import solve_snapshot
from .telemetry import emit, solve_telemetry
from .types import FactSnapshot, Solution

if TYPE_CHECKING:  # pragma: no cover
    from ..itinerary.models import ItineraryPlan

logger = logging.getLogger(__name__)

ENGINE_LEGACY = "legacy"
ENGINE_SHADOW = "shadow"
ENGINE_CPSAT = "cpsat"
ENGINES = (ENGINE_LEGACY, ENGINE_SHADOW, ENGINE_CPSAT)
ENV_FLAG = "TRIP_SOLVER"

SHADOW_SAMPLE_RATE = 0.05  # audit M6: ≤ 5% of generations

FALLBACK_DISCLOSURE = {
    "zh": "行程由现行引擎生成（新求解引擎未就绪/已回滚，TRIP_SOLVER=legacy 语义）",
    "en": "Itinerary generated by the current engine (new solver not ready "
    "or rolled back, TRIP_SOLVER=legacy semantics)",
}


class TripSolverError(RuntimeError):
    """Base for entry-adapter failures (fail-loud surface in tests)."""


class ServingNotReady(TripSolverError):
    """flag=cpsat was requested but the serving stack (P1-F assembly) is
    not landed — the caller must keep the cascade serving (M8 shape)."""


def engine_flag(env: Optional[dict] = None) -> str:
    """Resolved engine flag. Unknown values degrade to legacy with a
    warning — a typo in the env var must never half-switch the engine."""
    source = env if env is not None else os.environ
    value = str(source.get(ENV_FLAG, "") or "").strip().lower()
    if value in ENGINES:
        return value
    if value:
        logger.warning(
            "trip_solver: unknown %s=%r — degrading to legacy", ENV_FLAG, value
        )
    return ENGINE_LEGACY


def serving_ready() -> tuple[bool, str]:
    """Whether flag=cpsat can actually SERVE a plan (needs P1-F F-30
    materialisation). Checked before any model work: production never pays
    for a solve it cannot serve."""
    try:
        import app.services.trip_solver.assembly  # noqa: F401
    except ImportError:
        return False, "P1-F assembly not landed (F-30 materialisation missing)"
    return True, ""


def should_sample(key: str, rate: float = SHADOW_SAMPLE_RATE) -> bool:
    """Deterministic sampling gate (M6): stable per key, no RNG state."""

    bucket = int(hashlib.sha1(key.encode("utf-8")).hexdigest()[:8], 16) % 10000
    return bucket < int(rate * 10000)


@dataclass
class SolveOutcome:
    """What the adapter decided. `engine` is who SERVED; `requested` is
    what the flag asked for; `fallback=True` means the cascade served
    although cpsat was requested (not-ready or exception — M8 shape)."""

    engine: str
    requested: str
    solution: Optional[Solution] = None
    plan: "ItineraryPlan | None" = None  # F-30 servable plan (P1-F)
    telemetry: Optional[dict[str, Any]] = None
    fallback: bool = False
    disclosures: list[dict[str, str]] = field(default_factory=list)


def _legacy_outcome(requested: str) -> SolveOutcome:
    return SolveOutcome(engine=ENGINE_LEGACY, requested=requested)


def solve_trip(
    snapshot: FactSnapshot,
    *,
    flag: Optional[str] = None,
    budget_s: float = 3.0,
    hint: Optional[Solution] = None,
    fail_loud: bool = False,
    sample_key: Optional[str] = None,
    _ready: Optional[Callable[[], tuple[bool, str]]] = None,
) -> SolveOutcome:
    """F-35 entry point (synchronous — wrap in ``asyncio.to_thread``).

    - legacy → no model work, cascade serves (outcome.engine=legacy).
    - shadow → cascade serves; the model solves once for telemetry when
      ``sample_key`` passes :func:`should_sample` (M6 sampling).
    - cpsat → model serves when :func:`serving_ready`; pre-P1-F that is
      False → fallback outcome (cascade serves, disclosure attached).
      Exceptions on the model path: raised when ``fail_loud`` (tests),
      else fallback + telemetry + disclosure (production, M8).
    """
    requested = flag if flag is not None else engine_flag()
    if requested == ENGINE_LEGACY:
        return _legacy_outcome(requested)

    if requested == ENGINE_SHADOW:
        if sample_key is not None and not should_sample(sample_key):
            return _legacy_outcome(requested)
        try:
            solution = solve_snapshot(enrich(snapshot), budget_s=budget_s)
            record = emit(solve_telemetry(snapshot, solution, engine=ENGINE_SHADOW))
            return SolveOutcome(
                engine=ENGINE_LEGACY,  # the cascade serves in shadow mode
                requested=requested,
                solution=solution,
                telemetry=record,
            )
        except Exception as exc:  # shadow never affects serving
            logger.warning("trip_solver: shadow solve failed: %r", exc)
            if fail_loud:
                raise
            return _legacy_outcome(requested)

    # requested == cpsat
    ready_fn = _ready or serving_ready
    ready, reason = ready_fn()
    if not ready:
        record = emit(
            solve_telemetry(
                snapshot,
                None,
                engine=ENGINE_CPSAT,
                fallback_reason=reason,
            )
        )
        if fail_loud:
            raise ServingNotReady(reason)
        return SolveOutcome(
            engine=ENGINE_LEGACY,
            requested=requested,
            telemetry=record,
            fallback=True,
            disclosures=[dict(FALLBACK_DISCLOSURE)],
        )
    try:
        solution = solve_snapshot(  # F-24: hint seeds the re-solve (P4)
            enrich(snapshot), budget_s=budget_s, hint=hint
        )
        record = emit(
            solve_telemetry(
                snapshot, solution, engine=ENGINE_CPSAT, hint_used=hint is not None
            )
        )
        plan = None
        if solution.status in ("OPTIMAL", "FEASIBLE"):
            plan = assemble(
                solution, snapshot, lang=getattr(snapshot.request, "lang", "zh")
            )
        return SolveOutcome(
            engine=ENGINE_CPSAT,
            requested=requested,
            solution=solution,
            plan=plan,
            telemetry=record,
        )
    except Exception as exc:
        logger.exception("trip_solver: cpsat solve failed: %r", exc)
        if fail_loud:
            raise
        record = emit(
            solve_telemetry(
                snapshot,
                None,
                engine=ENGINE_CPSAT,
                fallback_reason="exception",
                error=repr(exc),
            )
        )
        return SolveOutcome(
            engine=ENGINE_LEGACY,
            requested=requested,
            telemetry=record,
            fallback=True,
            disclosures=[dict(FALLBACK_DISCLOSURE)],
        )
