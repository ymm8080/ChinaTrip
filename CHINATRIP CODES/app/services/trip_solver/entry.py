"""F-35 entry adapter — the only call path between legacy/api and the new
engine (P3, flag-gated; **code lands first, cutover stays gated**).

``TRIP_SOLVER`` env (M8 rollback = flip it back to ``legacy``; no data
migration — plan/session schemas are unchanged):

- ``legacy`` (default) — the existing cascade serves, untouched. This is
  the only behavior through P1/P2; the adapter is contract + telemetry.
- ``shadow`` — the cascade still serves; the model double-solves purely
  for F-36 telemetry / F-62 evidence. Audit M6 live sampling applies:
  ≤ 5 % of generations, max 1 extra solve per session — gate with
  :func:`should_sample` before calling.
- ``cpsat`` — the model engine serves. Pre-P1-F there is no plan
  materialisation (F-30), so :func:`serving_ready` is False and callers
  keep the cascade serving with a disclosure line — exactly the M8
  rollback shape. Exceptions inside the model path: **fail loud in
  tests**; in production → telemetry + legacy serving with disclosure
  (F-35). The P0 outbound gates run downstream of either engine.

The adapter is synchronous; callers invoke it via ``asyncio.to_thread``
(F-35). P4 edit re-solve passes the previous solution as ``hint``.
"""

