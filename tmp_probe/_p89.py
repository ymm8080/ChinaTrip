# -*- coding: utf-8 -*-
import io
NL = chr(10)
p = r"D:\CHINATRIP\CHINATRIP CODES\app\services\agent\plan.py"
t = io.open(p, encoding="utf-8", newline=None).read()

# 1) _finalize_wish_cities
start = t.index("    def _finalize_wish_cities(\n")
end = t.index("    async def _answer_wish_city(\n")
block1 = NL.join([
'    def _finalize_wish_cities(',
'        self, session: PlanSession, unresolved: list[tuple[str, dict]]',
'    ) -> str:',
'        """coverage 之后的追问收尾：落实写回已补上城市的剔除；仍空着',
'        的并入 pending_wish_cities（与旧 pending 去重），返回追问文本。',
'        2026-11-15：城市读会话（site_cities/绑定），不再读行。""";',
'        if not unresolved:',
'            return ""',
'        pending = list(session.pending_wish_cities)',
'        for wish, _row in unresolved:',
'            fresh_city = (session.site_cities.get(wish) or "").strip()',
'            if not fresh_city:',
'                _bound = (session.wish_bindings or {}).get(wish) or self._wish_bindings.get(',
'                    wish',
'                )',
'                fresh_city = str((_bound or {}).get("city") or "").strip()',
'            if fresh_city:',
'                pending = [p for p in pending if p != wish]',
'                continue',
'            if wish not in pending:',
'                pending.append(wish)',
'        session.pending_wish_cities = pending',
'        return wish_city_question(pending)',
'',
'',
])
t = t[:start] + block1 + t[end:]

# 2) _answer_wish_city: session-based (rows read dropped)
a_start = t.index("    async def _answer_wish_city(\n")
a_end = t.index("    async def _ensure_wishlist_coverage(\n")
block2 = NL.join([
'    async def _answer_wish_city(',
'        self, session: PlanSession, text: str',
'    ) -> tuple[PlanSession, str, ChangeSummary | None] | None:',
'        """心愿城市追问的答复轮：确定性解析不烧 LLM。点名的心愿按名字',
'        之后的片段取答复；只挂一条时整句话都算。可辨「都可以」（不绑',
'        城市）与「不要了」（心愿撤掉，保存物化时不建行/建 unwanted 行）。',
'        2026-11-15 用户拍板「心愿单只在保存/删除时进数据库」：答复只写',
'        会话（site_cities/wish_sources/must_visits），不再读写行。',
'        解析不出返回 None，正常走对话流程，不困住用户。"""',
'        if not session.pending_wish_cities:',
'            return None',
'        pending = list(session.pending_wish_cities)',
'        parts: list[str] = []',
'        answered: set[str] = set()',
'        for name in pending:',
'            seg: str | None = None',
'            if name in text:',
'                seg = text[text.index(name) + len(name) :]',
'                for other in pending:',
'                    if other != name and other in seg:',
'                        seg = seg[: seg.index(other)]',
'            elif len(pending) == 1:',
'                seg = text',
'            if seg is None:',
'                continue',
'            seg = seg.strip().strip(_WISH_SEG_TRIM)',
'            if _WISH_DROP_RE.search(seg):',
'                # 撤掉心愿：会话记录 dropped，物化时落 unwanted 行',
'                meta = dict((session.wish_sources or {}).get(name) or {})',
'                meta["dropped"] = True',
'                meta.setdefault("note", L("来自聊天", "From chat"))',
'                session.wish_sources = {',
'                    **(session.wish_sources or {}),',
'                    name: meta,',
'                }',
'                if name in (session.must_visits or []):',
'                    session.must_visits = [',
'                        m for m in session.must_visits if not _same_site(m, name)',
'                    ]',
'                parts.append(',
'                    L(',
'                        f"「{name}」已从心愿单移除",',
'                        f\\"{name}\\" removed from your wishlist",',
'                    )',
'                )',
'                answered.add(name)',
'            elif _WISH_ANY_RE.search(seg):',
'                parts.append(',
'                    L(',
'                        f"「{name}」按不限城市记",',
'                        f\\"{name}\\" noted with no city preference",',
'                    )',
'                )',
'                answered.add(name)',
'            else:',
'                city = _match_city_token(seg) or (',
'                    _match_city_token(text) if len(pending) == 1 else None',
'                )',
'                if city:',
'                    session.site_cities[name] = city',
'                    meta = dict((session.wish_sources or {}).get(name) or {})',
'                    meta["city"] = city',
'                    session.wish_sources = {',
'                        **(session.wish_sources or {}),',
'                        name: meta,',
'                    }',
'                    parts.append(',
'                        L(f"「{name}」已记到{city}", f\\"{name}\\" noted under {city}")',
'                    )',
'                    answered.add(name)',
'        if not answered:',
'            return None',
'        session.pending_wish_cities = [n for n in pending if n not in answered]',
'        reply = L("；".join(parts), "; ".join(parts))',
'        remaining = wish_city_question(session.pending_wish_cities)',
'        if remaining:',
'            reply = (',
'                L(f"{reply}。{remaining}", f"{reply}. {remaining}")',
'                if reply',
'                else remaining',
'            )',
'        session.history.append(ChatMessage(role="assistant", content=reply))',
'        return session, reply, None',
'',
'',
])
t = t[:a_start] + block2 + t[a_end:]
io.open(p, "w", encoding="utf-8", newline="\r\n").write(t)
print("finalize+answer ok")
